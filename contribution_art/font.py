def _normalize(rows):
    """Convert '#' / '.' rows to '1' / '0' rows."""
    norm = []
    for r in rows:
        norm.append(''.join('1' if c == '#' else '0' for c in r))
    return norm


# Normalized, validated font: char -> list of 7 '0'/'1' strings.
FONT = {}
for _ch, _rows in FONT_RAW.items():
    if len(_rows) != FONT_HEIGHT:
        raise ValueError("glyph %r must have 7 rows" % _ch)
    _w = len(_rows[0])
    for _r in _rows:
        if len(_r) != _w:
            raise ValueError("glyph %r rows must be equal width" % _ch)
    FONT[_ch] = _normalize(_rows)


def get_glyph(char):
    """Return the 7-row '0'/'1' glyph for char.

    Lowercase is upper-cased. Unknown characters map to '?' if
    available, else a blank 5-wide glyph. Never raises.
    """
    if not char:
        return _normalize(["....."] * FONT_HEIGHT)
    c = char.upper()
    if c in FONT:
        return FONT[c]
    if '?' in FONT:
        return FONT['?']
    return ['00000'] * FONT_HEIGHT


def glyph_width(char):
    """Return pixel width of a single character."""
    return len(get_glyph(char)[0])


