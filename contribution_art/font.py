def get_mini_glyph(char):
    """3-row glyph for stacked mode. Uppercase fallback; never raises."""
    if not char:
        return ['000'] * MINI_HEIGHT
    c = char.upper()
    if c in MINI:
        return MINI[c]
    if '?' in MINI:
        return MINI['?']
    return ['000'] * MINI_HEIGHT
